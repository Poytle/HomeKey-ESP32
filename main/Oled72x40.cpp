Oled72x40::Oled72x40(gpio_num_t sda, gpio_num_t scl) : m_sda(sda), m_scl(scl) {
    m_frame[0] = CONTROL_DATA;
}

Oled72x40::~Oled72x40() {
    if (m_dev) {
        i2c_master_bus_rm_device(m_dev);
    }
    if (m_bus) {
        i2c_del_master_bus(m_bus);
    }
}

bool Oled72x40::begin() {
    i2c_master_bus_config_t buscfg = {};
    buscfg.i2c_port = -1;
    buscfg.sda_io_num = m_sda;
    buscfg.scl_io_num = m_scl;
    buscfg.clk_source = I2C_CLK_SRC_DEFAULT;
    buscfg.glitch_ignore_cnt = 7;
    buscfg.flags.enable_internal_pullup = true;

    esp_err_t err = i2c_new_master_bus(&buscfg, &m_bus);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "i2c_new_master_bus failed: %s", esp_err_to_name(err));
        return false;
    }
    if (i2c_master_probe(m_bus, OLED_I2C_ADDR, XFER_TIMEOUT_MS) != ESP_OK) {
        return false;
    }

    i2c_device_config_t devcfg = {};
    devcfg.dev_addr_length = I2C_ADDR_BIT_LEN_7;
    devcfg.device_address = OLED_I2C_ADDR;
    devcfg.scl_speed_hz = I2C_SPEED_HZ;

    err = i2c_master_bus_add_device(m_bus, &devcfg, &m_dev);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "i2c_master_bus_add_device failed: %s", esp_err_to_name(err));
        m_dev = nullptr;
        return false;
    }

    static constexpr uint8_t DISPLAY_ON[] = {0xAF};
    if (!sendCommands(INIT_SEQUENCE, sizeof(INIT_SEQUENCE))) {
        return false;
    }
    clear();
    return flush() && sendCommands(DISPLAY_ON, sizeof(DISPLAY_ON));
}

void Oled72x40::clear() {
    std::fill(m_frame.begin() + 1, m_frame.end(), 0);
}

void Oled72x40::text(size_t row, const char* str) {
    if (row >= kRows) {
        return;
    }
    uint8_t* line = m_frame.data() + 1 + row * WIDTH;
    memset(line, 0, WIDTH);
    for (size_t col = 0; col < kCols && str[col] != '\0'; ++col) {
        const char c = (str[col] < FONT_FIRST || str[col] > FONT_LAST) ? '?' : str[col];
        memcpy(line + col * CELL_WIDTH, FONT[c - FONT_FIRST], GLYPH_WIDTH);
    }
}

bool Oled72x40::flush() {
    static constexpr uint8_t WINDOW[] = {
        0x21, COLUMN_OFFSET, COLUMN_OFFSET + WIDTH - 1, // column range
        0x22, 0, PAGES - 1,                             // page range
    };
    if (!sendCommands(WINDOW, sizeof(WINDOW))) {
        return false;
    }
    return i2c_master_transmit(m_dev, m_frame.data(), m_frame.size(), XFER_TIMEOUT_MS) == ESP_OK;
}

bool Oled72x40::sendCommands(const uint8_t* cmds, size_t len) {
    uint8_t buf[1 + sizeof(INIT_SEQUENCE)];
    buf[0] = CONTROL_COMMAND;
    memcpy(buf + 1, cmds, len);
    return i2c_master_transmit(m_dev, buf, len + 1, XFER_TIMEOUT_MS) == ESP_OK;
}
